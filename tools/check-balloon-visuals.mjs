import assert from 'node:assert/strict';
import * as THREE from '../game/vendor/three.module.min.js';
import {createBalloonVisuals} from '../game/balloon-visuals.js';
const api=createBalloonVisuals(THREE),b=api.balloon(),ground=api.balloon({ground:true}),scene=new THREE.Scene();
scene.add(b);const bounds=new THREE.Box3().setFromObject(b),size=bounds.getSize(new THREE.Vector3());
assert(size.x>.3&&size.y>.3&&size.x<.5&&size.y<.5,'source balloon remains hand-sized');
assert(b.userData.sprite.isSprite&&ground.userData.sprite.isSprite,'source RGB drives flight and ground');
api.animateBalloon(b,.12);assert(Math.abs(b.scale.x-b.scale.y)>.01,'elastic deformation');
const before=ground.scale.toArray();api.animateBalloon(ground,.12);assert.deepEqual(ground.scale.toArray(),before,'ground pickup does not wobble');
api.popLatex(scene,new THREE.Vector3(1,2,3));api.updateLatex(.1);
const burst=scene.children.find(x=>x!==b),splash=burst.children[0];assert(splash.isSprite);assert(splash.scale.x>.42);assert(splash.material.opacity<=1);
for(let i=0;i<100;i++)api.updateLatex(.02);assert.equal(scene.children.length,1,'impact visuals expire');
for(let i=0;i<12;i++)api.popLatex(scene,new THREE.Vector3());assert.equal(scene.children.length,9,'bounded bursts');
api.clearLatex();assert.equal(scene.children.length,1);let disposed=0;b.userData.sprite.material.addEventListener('dispose',()=>disposed++);b.userData.dispose();assert.equal(disposed,1);
console.log('PASS source balloon hand scale, ground stability, flight deformation, bounded splash expansion/expiry and material disposal');
